import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.dirname(fileURLToPath(import.meta.url));
const require=createRequire(import.meta.url),{build}=require('esbuild');
const output=path.join(root,'.ssr-check.cjs');
try{
 await build({entryPoints:[path.join(root,'CinematicExperience.jsx')],bundle:true,platform:'node',format:'cjs',packages:'external',outfile:output,logLevel:'silent',define:{'process.env.NODE_ENV':'"production"'}});
 const {CinematicExperience,CHAPTERS,CinemaMath}=require(output),React=require('react'),{renderToString}=require('react-dom/server');
 const cinema=renderToString(React.createElement(CinematicExperience));
 assert.ok(cinema.includes('cinema-stage'),'The default entry is the full-screen cinematic canvas');
 assert.ok(!cinema.includes('studio-workspace')&&!cinema.includes('density-plot')&&!cinema.includes('type="range"'),'The opening contains no dashboard, line plot or sliders');
 for(const text of ['The connected field.','384','264','E₈','Explore','LIVE GEOMETRY'])assert.ok(cinema.includes(text),text+' must be present');
 for(const chapter of CHAPTERS)assert.ok(!renderToString(React.createElement(CinemaMath,{tex:chapter.tex,block:true})).includes('katex-error'),'Each cinematic identity must typeset');
 await build({entryPoints:[path.join(root,'StudioApp.jsx')],bundle:true,platform:'node',format:'cjs',packages:'external',outfile:output,logLevel:'silent',define:{'process.env.NODE_ENV':'"production"'}});
 delete require.cache[require.resolve(output)];
 const {IntegralStudio,Definitions}=require(output);
 const html=renderToString(React.createElement(IntegralStudio));
 const proof=renderToString(React.createElement(Definitions,{onClose(){}}));
 assert.ok(!html.includes('katex-error')&&!proof.includes('katex-error'),'All retained study identities typeset');
 assert.equal((html.match(/type="range"/g)||[]).length,5,'All existing study controls remain accessible');
 const offline=fs.readFileSync(path.resolve(root,'../../../output/PerfectPower_Integral_Studio.html'),'utf8');
 const markup=offline.slice(0,offline.indexOf('<script>'))+offline.slice(offline.lastIndexOf('</script>')+9);
 assert.ok(!/<script[^>]+src=/.test(markup),'Offline JavaScript is embedded');
 assert.ok(!/<link[^>]+rel="stylesheet"/.test(markup),'Offline styles and math fonts are embedded');
 assert.equal((offline.match(/id="integral-studio"/g)||[]).length,1,'One app mount');
 console.log('Default cinematic canvas, absence of dashboard/plots/sliders, all four cinematic equations, complete retained study and offline embedding verified. This is server-render and source QA, not browser interaction QA.');
}finally{fs.rmSync(output,{force:true});}
